let changesCount = 0;

for (const { from, to } of replacements) {
  // Используем split/join для безопасной замены всех вхождений конкретной строки
  const newContent = content.split(from).join(to);
  if (newContent !== content) {
    content = newContent;
    changesCount++;
  }
}

fs.writeFileSync(filePath, content, 'utf-8');
console.log(`✅ Готово! Исправлено ${changesCount} типов опечаток. Нормальные пробелы не тронуты.`);
