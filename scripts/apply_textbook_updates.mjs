function loadBook(file, variable) {
  const source = fs.readFileSync(path.join(partsDir, file), "utf8");
  const context = { window: {} };
  vm.createContext(context);
  vm.runInContext(source, context, { filename: file });
  return context.window[variable];
}

function writeBook(file, variable, book) {
  const text = `// Автор: ${book.authors?.[0]?.fullName || book.authors?.[0]?.name || variable}\nwindow.${variable} = ${JSON.stringify(book, null, 2)};\n`;
  fs.writeFileSync(path.join(partsDir, file), text);
}

function allSections(book) {
  return book.chapters.flatMap((chapter) => chapter.sections.map((section) => ({ chapter, section })));
}

function linkFor(book, needle) {
  const found = allSections(book).find(({ section }) => {
    const text = `${section.title} ${section.lead || ""}`.toLowerCase();
    return text.includes(needle.toLowerCase());
  });
  return `#${found?.section.id || allSections(book)[0]?.section.id || ""}`;
}

function imageFiles(authorId) {
  const dir = path.join(root, "images", authorId);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir)
    .filter((name) => /\.(jpe?g|png|webp|gif|svg)$/i.test(name))
    .slice(0, 10)
    .map((name) => `images/${authorId}/${name}`);
}

function hasBlock(section, type) {
  return (section.blocks || []).some((block) => block.type === type);
}

function ensureOpeningBlocks(book, profile, authorId) {
  const first = allSections(book)[0]?.section;
  if (!first) return;
  first.blocks ||= [];

  if (!hasBlock(first, "terms")) {
    first.blocks.unshift({
      type: "terms",
      title: "Ключевые термины творчества автора",
      items: profile.terms.map(([term, text, needle]) => ({
        term,
        text,
        href: linkFor(book, needle),
      })),
    });
  }

  const existingGallery = hasBlock(first, "gallery");
  const images = imageFiles(authorId);
  if (!existingGallery && images.length) {
    first.blocks.splice(1, 0, {
      type: "gallery",
      title: "Фотоматериалы к авторскому разделу",
      images: images.map((src, index) => ({
        src,
        alt: `${profile.name}: фотоматериал ${index + 1}`,
        caption: `${profile.name}. Материал ${index + 1}`,
      })),
    });
  }

  if (!hasBlock(first, "video")) {
    first.blocks.push({
      type: "video",
      title: `Видео из хранилища ${profile.kind === "poetry" ? "поэзии" : "прозы"}`,
      text: "Видеоматериалы по творчеству автора доступны по ссылке.",
      url: "",
      storage: profile.kind,
    });
  }
}

function ensureCritics(book, profile, authorId) {
  if (book.chapters.some((chapter) => chapter.id === `${authorId}-critics`)) return;
  const insertAt = Math.max(0, book.chapters.findIndex((chapter) => /summary|итог/i.test(chapter.id + " " + chapter.title)));
  const chapter = {
    id: `${authorId}-critics`,
    authorId,
    number: "Критика",
    title: "Мнение критиков и читателей",
    sections: [{
      id: `${authorId}-critics-view`,
      title: "Как воспринимали автора и произведения",
      lead: `Этот блок помогает увидеть, что произведения автора ${profile.name} важны не только как школьный материал, но и как часть большого разговора о войне, памяти и ответственности.`,
      blocks: [
        { type: "h2", text: "Что отмечали критики" },
        { type: "p", text: profile.critics },
        { type: "h2", text: "Почему это важно подростку" },
        { type: "p", text: "Критическое мнение помогает читать военную литературу не как набор дат и сюжетов, а как разговор о выборе человека. Для подростка это особенно важно: герои этих произведений часто молоды, ошибаются, боятся, но именно в трудных обстоятельствах становится видно, что такое достоинство." },
        { type: "note", title: "Вопрос для обсуждения", text: `Согласны ли вы с тем, что произведения автора ${profile.name} нужны современному подростку именно для разговора о личной ответственности? Ответ подтвердите одним эпизодом или образом.` },
      ],
    }],
  };
  if (insertAt > 0) book.chapters.splice(insertAt, 0, chapter);
  else book.chapters.push(chapter);
}

